			q'{create table GD_ENT_CAPITAL_CRED_M91 as
			SELECT /*+ ordered */
				ENTIDADE_RISCO.CDPERSON
				,NVL(SUM(DECODE(GARANTIA.CDTIPGAR, 'A', (GARANTIA.IMPCONCO * PKG_FORMULAS_COSEC.FUN_TAXA_CAMBIO(PROPOSTA.CDMOEDA) * DECODE(PROPOSTA.INDCOASEG, 'N', 1, 1 - (PKG_FORMULAS_COSEC.FUN_PERCENTAGEM_TOTAL_COAS(PROPOSTA.CDUNIECO, PROPOSTA.CDRAMO, PROPOSTA.SWESTADO, PROPOSTA.NMPOLIZA, SYSDATE) / 100))), 0)), 0) CAPITAL_DINAMICO
				,NVL(SUM(CASE 
							WHEN GARANTIA.CDTIPGAR != 'A'
								AND GARANTIA.CDRAMO IN (SELECT CDRAMO FROM TRAMOS WHERE CDTIPRAM = 1)
								THEN (GARANTIA.IMPCONCO * PKG_FORMULAS_COSEC.FUN_TAXA_CAMBIO(PROPOSTA.CDMOEDA) * DECODE(PROPOSTA.INDCOASEG, 'N', 1, 1 - (PKG_FORMULAS_COSEC.FUN_PERCENTAGEM_TOTAL_COAS(PROPOSTA.CDUNIECO, PROPOSTA.CDRAMO, PROPOSTA.SWESTADO, PROPOSTA.NMPOLIZA, SYSDATE) / 100)))
							ELSE 0
							END), 0) CAPITAL_NOMINATIVO
				,NVL(SUM(CASE 
							WHEN GARANTIA.CDTIPGAR != 'A'
								AND GARANTIA.CDRAMO IN (SELECT CDRAMO FROM TRAMOS WHERE CDTIPRAM = 1)
								THEN DECODE(GARANTIA.IMPSOLCO, 0, 0, 1)
							ELSE 0
							END), 0) N_GARANTIAS_NOMINATIVAS
