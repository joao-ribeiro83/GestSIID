  CRIA_INFO_ENTIDADES_M91
IS
  NRESULT NUMBER;

  VALIDA_OBJ NUMBER;

  vTIME1 date;
  vTIME2 date;
  vTIME3 date;
  vTIME4 date;
  vTIME5 date;
