		SELECT COUNT(1)
		INTO VALIDA_OBJ
		FROM USER_TABLES
		WHERE TABLE_NAME = 'GD_ENT_CAPITAL_CRED_M91';

		DBMS_OUTPUT.put_line('GD_ENT_CAPITAL_CRED_M91 - ' || VALIDA_OBJ);

		if VALIDA_OBJ > 0 then
			DBMS_OUTPUT.put_line('drop table GD_ENT_CAPITAL_CRED_M91');
