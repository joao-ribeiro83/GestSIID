					SELECT CHAVE
					FROM CFG_VALORES_DOMINIO
					WHERE DOMINIO_ID = 'EXCLUSAO_RISCO'
					)
				AND z.cdtipora = '2'
			GROUP BY ENTIDADE_RISCO.CDPERSON}';

		DBMS_OUTPUT.put_line('create table as GD_ENT_CAPITAL_CAU_M91 - END');

		execute immediate 'CREATE UNIQUE INDEX "GD_ENT_CAPITAL_CAU_M91_INDX" ON "GD_ENT_CAPITAL_CAU_M91" ("CDPERSON") COMPUTE STATISTICS';

