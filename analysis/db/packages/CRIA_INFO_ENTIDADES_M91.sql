		SELECT COUNT(1)
		INTO VALIDA_OBJ
		FROM USER_TABLES
		WHERE TABLE_NAME = 'GD_ENTIDADES_M91';

		DBMS_OUTPUT.put_line('GD_ENTIDADES_M91 - ' || VALIDA_OBJ);

		if VALIDA_OBJ > 0 then
            DBMS_OUTPUT.put_line('drop table GD_ENTIDADES_M91');
			execute immediate 'drop table GD_ENTIDADES_M91';
            DBMS_OUTPUT.put_line('drop table GD_ENTIDADES_M91 - end');
		end if;

        DBMS_OUTPUT.put_line('create table as GD_ENTIDADES_M91');
		execute immediate 
			q'{create table GD_ENTIDADES_M91 as
			SELECT /*+ ordered USE_HASH(PESSOA ENTIDADE) USE_NL(PAIS desc_cae desccae)*/
				PESSOA.CDIDEPER
				,PESSOA.CDPERSON
				,PESSOA.DSNOMBRE
				,PESSOA.CDPAIS
				,PAIS.DESCRIPL desc_pais
				,ENTIDADE.CDCAE
				,desc_cae.DESCRIPL setor_atividade
			FROM MPERSONA PESSOA
				,CO_ENTIDAD ENTIDADE
				,TMANTENI PAIS
				,TMANTENI desc_cae
				,co_caes desccae
			WHERE 1 = 1
				AND desc_cae.cdtabla(+) = 'CO_GCAES'
				AND desc_cae.codigo(+) = desccae.CDGRUCAE2
				AND desccae.cdcae(+) = ENTIDADE.cdcae
				AND ENTIDADE.CDPERSON = PESSOA.CDPERSON
				AND PAIS.CODIGO = PESSOA.CDPAIS
				AND PAIS.CDTABLA = 'TPAISES'
				AND NVL(PESSOA.FECBAJA, TO_DATE('01-01-2100', 'DD-MM-YYYY')) >= SYSDATE}';

		DBMS_OUTPUT.put_line('create table as GD_ENTIDADES_M91 - end');

		execute immediate 'CREATE UNIQUE INDEX "GD_ENTIDADES_M91_INDX" ON "GD_ENTIDADES_M91" ("CDPERSON") COMPUTE STATISTICS';

		commit;

	exception
		when others then
			DBMS_OUTPUT.put_line(sqlerrm);
	end;

	DBMS_STATS.GATHER_TABLE_STATS(ownname => '"SIID_TESTES"', tabname => '"GD_ENTIDADES_M91"', estimate_percent => 100);
	DBMS_STATS.GATHER_INDEX_STATS('"SIID_TESTES"', '"GD_ENTIDADES_M91_INDX"', estimate_percent => 100);

	vTIME2 := sysdate;
	VALIDA_OBJ := 0;

