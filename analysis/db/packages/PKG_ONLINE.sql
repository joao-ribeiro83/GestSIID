  FUNCTION TEST_KEY( P_KEY    IN VARCHAR2
                   , P_ORIGEM IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2
  IS
    pragma autonomous_transaction;

    L_LOGIN VARCHAR2(200);
  BEGIN
    IF  P_KEY IS NULL
	 OR NVL(P_ORIGEM,'') = '' THEN
	  ROLLBACK;
	  RETURN '0';
	END IF;

	SELECT
	  USER_ID||'/'||USER_SECURITY.decrypt(PASSWORD)||'/'||AMBIENTE
	INTO
	  L_LOGIN
	FROM
	  S$ONLINE
	WHERE
	    ID = hextoraw(P_KEY)
--	AND ORIGEM_IP = P_ORIGEM
	AND USADO_BN = 'N'
	AND ENTRADA+VALIDADE/(24*60*60) >= SYSDATE
	FOR UPDATE;

	UPDATE
	  S$ONLINE
	SET
	  USADO_BN = 'S'
	WHERE
	  ID = hextoraw(P_KEY);

	COMMIT;

	RETURN L_LOGIN;

  EXCEPTION
    WHEN OTHERS THEN
	  ROLLBACK;
	  RETURN '0';
  END TEST_KEY;

  /*
  -* NOME      : VALIDA_UE
  -* OBJECTIVO : TESTA SE MODELO TEM UNIDADE ECONOMICA VALIDA COM O UTILIZADOR
  -* UTILIZACAO: PKG_ONLINE.VALIDA_UE(DOC_ID) = 'S';
  -* AUTOR     : ALDO TITA
  -* DATA      : 02-11-2012
  -* VERS?O    : 1.0
  -*
  -* ULTIMAS ALTERAC?ES
  -*
  -*   DATA       VERSAO AUTOR           DESCRIC?O
  -*   ========== ====== =============== =================================================
  -*/

FUNCTION VALIDA_UE( P_ID IN SVR_DOCUMENTOS.ID%TYPE, P_REPORT_ID IN SVR_DOCUMENTOS.REPORT_ID%TYPE,
  P_PARAMETRO04  IN SVR_DOCUMENTOS.PARAMETRO04%TYPE,P_PARAMETRO05  IN SVR_DOCUMENTOS.PARAMETRO05%TYPE,
  P_PARAMETRO06  IN SVR_DOCUMENTOS.PARAMETRO06%TYPE,P_PARAMETRO07  IN SVR_DOCUMENTOS.PARAMETRO07%TYPE) RETURN VARCHAR2
  IS
  V_PARAMETRO VARCHAR(100);
  V_VALOR_UE  NUMBER;
  V_SQL       VARCHAR(4000);
  V_RETURN    NUMBER;
  BEGIN

      /*verificar qual o parametro que diz respeito a unidade economica*/
      SELECT
        N_PARAMETRO
      INTO
        V_PARAMETRO
      FROM
        SVR_PARAMETROS_REPORT PARAMETROS
      WHERE 1=1
      AND P_REPORT_ID = PARAMETROS.REPORT_ID
      AND UPPER(PARAMETROS.NOME) ='P_CDUNIECO'
      AND PARAMETROS.VALIDO='S';

      IF V_PARAMETRO=4 THEN
        V_VALOR_UE := P_PARAMETRO04;
      ELSIF V_PARAMETRO=5 THEN
        V_VALOR_UE := P_PARAMETRO05;
      ELSIF V_PARAMETRO=6 THEN
        V_VALOR_UE := P_PARAMETRO06;
      ELSE
        V_VALOR_UE := P_PARAMETRO07;
      END IF;

      /* VALIDAR SE O UTILIZADOR TEM ACESSO AO DOCUMENTO */
      V_SQL :=
     'SELECT '||
     '  ''S'' '||
     'FROM '||
     ' R_UNIDAUSR     UNI '||
     'WHERE '||
     '    UNI.CDUNIECO ='''||V_VALOR_UE||''' '||
     'AND UNI.CDIDUSR= user ';

      BEGIN
        EXECUTE IMMEDIATE V_SQL INTO V_RETURN;

      EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_RETURN:= 'N';
      END;

      RETURN V_RETURN;

  EXCEPTION
    WHEN OTHERS THEN
        RETURN 'S';
  END VALIDA_UE;

  FUNCTION F_INS_ENCRIPT(P_PASSWORD VARCHAR2, P_STRING VARCHAR2) RETURN VARCHAR2 IS
    L_RETURN_STRING  VARCHAR2(1000);
	BEGIN

	dbms_obfuscation_toolkit.DESEncrypt(input_string=>RPAD(P_STRING,32,CHAR_RESERV),
                                         key_string=>RPAD(P_PASSWORD,32,CHAR_RESERV),
                                         encrypted_string=>L_RETURN_STRING);

	RETURN L_RETURN_STRING;

  EXCEPTION
    WHEN OTHERS THEN
        --PCK_GEN.P_PUT_ERROR;
        RAISE;
  END F_INS_ENCRIPT;

END PKG_ONLINE;
