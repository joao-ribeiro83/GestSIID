PACKAGE BODY "PKG_ONLINE"
AS
  PACOTE         CONSTANT VARCHAR2(100):='PKG_ONLINE';
  V_PACOTE       CONSTANT VARCHAR2(100):='0.1';
    /*
  -*
  -* ULTIMAS ALTERAC?ES AO PACKAGE
  -*
  -*   DATA       VERSAO AUTOR           DESCRIC?O
  -*   ========== ====== =============== ===================================================
  -*   11-02-2010    1.0 Jose Viegas     Criacao do package
  */
  VERSAO         CONSTANT VARCHAR2(100):= '2010.01.01';
  DATA_VERSAO    CONSTANT DATE:= TO_DATE('15-04-2010 11:26:03','DD-MM-YYYY HH24:MI:SS');
  AUTOR_PACKAGE  CONSTANT VARCHAR2(100):='JOSE VIEGAS';
  AUTOR_VERSAO   CONSTANT VARCHAR2(100):='01.01';

  /*
  -* NOME      : GET_PACKINFO
  -* OBJECTIVO : MANTER INFORMAC?O SOBRE VERS?O DO PACKAGE
  -* UTILIZACAO: PKG_CFG_UTIL.GET_PACKINFO ( 'VERSAO' );
  -* AUTOR     : Eng. Jose Viegas
  -* DATA      : 25-11-2004
  -* VERS??O    : 1.0
  -*
  -* ULTIMAS ALTERAC?ES
  -*
  -*   DATA       VERSAO AUTOR           DESCRIC?O
  -*   ========== ====== =============== =================================================
  -*/
  FUNCTION GET_PACKINFO ( P_TIPO_INFO VARCHAR2 DEFAULT 'COMPLETE' ) RETURN VARCHAR2 IS
    AUX VARCHAR2(200);
  BEGIN
    IF P_TIPO_INFO = INFO_VERSAO THEN  /* DEVOLVE VERS?O DO PACKAGE */
      RETURN 'v'||TO_CHAR(VERSAO);
    ELSIF P_TIPO_INFO = INFO_DATA_VERSAO THEN
      RETURN TO_CHAR(DATA_VERSAO,'YYYY-MM-DD HH24:MI');
    ELSIF P_TIPO_INFO = INFO_AUTOR_PACKAGE THEN
      RETURN AUTOR_PACKAGE;
    ELSIF P_TIPO_INFO = INFO_AUTOR_VERSAO THEN
      RETURN AUTOR_VERSAO;
    ELSIF P_TIPO_INFO = INFO_DATA_PACKAGE THEN
      BEGIN
        SELECT
          TO_CHAR(CREATED,'YYYY-MM-DD HH24:MI')
        INTO
          AUX
        FROM
          ALL_OBJECTS
        WHERE
            OBJECT_NAME=PACOTE
        AND OBJECT_TYPE='PACKAGE BODY'
        AND OWNER = (SELECT USERNAME FROM USER_USERS);
        RETURN AUX;
      EXCEPTION
        WHEN OTHERS THEN
         RETURN PACOTE||' v'||VERSAO||'('||TO_CHAR(DATA_VERSAO,'YYMMDDHH24MI')||')';
      END;
    ELSIF P_TIPO_INFO = INFO_DATA_INSTALACAO THEN
      BEGIN
        SELECT
          TO_CHAR(LAST_DDL_TIME,'YYYY-MM-DD HH24:MI')
        INTO
          AUX
        FROM
          ALL_OBJECTS
        WHERE
            OBJECT_NAME=PACOTE
        AND OBJECT_TYPE='PACKAGE BODY'
        AND OWNER = (SELECT USERNAME FROM USER_USERS);
        RETURN AUX;
      EXCEPTION
        WHEN OTHERS THEN
         RETURN PACOTE||' v'||VERSAO||'('||TO_CHAR(DATA_VERSAO,'YYMMDDHH24MI')||')';
      END;
    ELSIF P_TIPO_INFO = INFO_OWNER THEN
      SELECT USERNAME INTO AUX FROM USER_USERS;
      RETURN AUX;
    ELSE
      RETURN PACOTE||' v'||VERSAO||'('||TO_CHAR(DATA_VERSAO,'YYMMDDHH24MI')||')';
    END IF;
  END GET_PACKINFO;


  /*
  -* NOME      : OPEN_GATE
  -* OBJECTIVO : ABRIR ENTRADA PARA CONSULTA ONLINE
  -* UTILIZACAO: KEY:=PKG_ONLINE.OPEN_GATE(USER, PASS, IP, HOST, SO, USER);
  -* AUTOR     : Eng. Jose Viegas
  -* DATA      : 15-04-2010
  -* VERS?O    : 1.0
  -*
  -* ULTIMAS ALTERAC?ES
  -*
  -*   DATA       VERSAO AUTOR           DESCRIC?O
  -*   ========== ====== =============== =================================================
  -*/
  FUNCTION OPEN_GATE( P_USER      IN VARCHAR2 DEFAULT USER
                    , P_PASS      IN VARCHAR2
					, P_AMBIENTE  IN VARCHAR2 DEFAULT NULL
					, P_HOST_IP   IN VARCHAR2 DEFAULT NULL
					, P_HOST_NAME IN VARCHAR2 DEFAULT NULL
					, P_HOST_SO   IN VARCHAR2 DEFAULT NULL
					, P_HOST_USER IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2
  IS

    pragma autonomous_transaction;

    L_KEY RAW(16):= SYS_GUID();
	L_AMBIENTE VARCHAR2(30):=P_AMBIENTE;
	L_VALIDADE NUMBER;
	L_ENCRYPTED_PASS VARCHAR(1000);
	L_AMB_KEY VARCHAR(100);

  BEGIN

    IF P_PASS IS NULL THEN
	  ROLLBACK;
	  RETURN NULL;
	END IF;

	IF L_AMBIENTE IS NULL THEN
	  SELECT
	    USERNAME
	  INTO
	    L_AMBIENTE
	  FROM
	    USER_USERS;
    END IF;

	BEGIN
	  SELECT
  	    VALOR
  	  INTO
        L_VALIDADE
	  FROM
        S$PARAMETROS
	  WHERE
	    ID = 'VALIDADE_KEY';
	EXCEPTION
	  WHEN OTHERS THEN
	    L_VALIDADE:=30;
	END;

	L_ENCRYPTED_PASS := USER_SECURITY.encrypt(P_PASS);

	DBMS_OUTPUT.PUT_LINE(L_AMBIENTE||' -> '||P_USER||'!');

    INSERT
     INTO S$ONLINE
    (
      ID
    , USER_ID
    , PASSWORD
    , AMBIENTE
    , ENTRADA
    , VALIDADE
    , ORIGEM_IP
    , ORIGEM_HOST
    , ORIGEM_SO
    , ORIGEM_USER
    )
    VALUES
    (
      L_KEY
    , P_USER
    , L_ENCRYPTED_PASS
    , L_AMBIENTE
    , SYSDATE
    , L_VALIDADE
    , P_HOST_IP
    , P_HOST_NAME
    , P_HOST_SO
    , P_HOST_USER
    );

	IF L_AMBIENTE = 'COSEC' THEN
		L_AMB_KEY := rawtohex(L_KEY);
		L_AMB_KEY := '?id=' || L_AMB_KEY || '&' || 'amb=P';
	ELSE
		L_AMB_KEY := rawtohex(L_KEY);
		L_AMB_KEY := '?id=' || L_AMB_KEY || '&' || 'amb=T';
    END IF;

	COMMIT;

    RETURN L_AMB_KEY;

  EXCEPTION
    WHEN OTHERS THEN
	  ROLLBACK;
	  RETURN NULL;
  END OPEN_GATE;

  /*
  -* NOME      : TEST_KEY
  -* OBJECTIVO : TESTA CHAVE FORNECIDA PARA ENTRAR ONLINE
  -* UTILIZACAO: LOGIN:=PKG_ONLINE.TEST_KEY(KEY, ORIGEM);
