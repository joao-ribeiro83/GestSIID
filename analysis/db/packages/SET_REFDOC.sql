-- SET_REFDOC (owner: SIID_TESTES)


-- ===== FUNCTION =====

FUNCTION SET_REFDOC( P_REF IN VARCHAR2, P_DOC_ID IN NUMBER DEFAULT -1) RETURN VARCHAR2
IS
  cResult VARCHAR2(20);
BEGIN
  IF NVL(P_DOC_ID,-1) >= 0 THEN

    SELECT
   N_REFERENCIA
 INTO
   cResult
 FROM
   SVR_DOCUMENTOS
 WHERE
   ID = P_DOC_ID;

 IF cResult IS NULL THEN

      UPDATE
     SVR_DOCUMENTOS
      SET
     N_REFERENCIA = P_REF
      WHERE
     ID = P_DOC_ID;

      COMMIT;

 END IF;

  END IF;

  return '1';

EXCEPTION
  WHEN OTHERS THEN
    RETURN '-1';
END SET_REFDOC;

