							WHEN CAPITAL.CDTIPGAR != 'A'
								AND CAPITAL.CDTIPRAM = 1
								THEN DECODE(CAPITAL.IMPSOLCO, 0, 0, 1)
							ELSE 0
							END), 0) N_GARANTIAS_NOMINATIVAS
