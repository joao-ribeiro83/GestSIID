	DBMS_STATS.GATHER_INDEX_STATS('"SIID_TESTES"', '"GD_ENTIDADES_M91B_INDX"', estimate_percent => 100);
	DBMS_STATS.GATHER_INDEX_STATS('"SIID_TESTES"', '"GD_ENTIDADES_M91B_INDX_2"', estimate_percent => 100);

	vTIME2 := sysdate;
	VALIDA_OBJ := 0;

	begin

		SELECT COUNT(1)
		INTO VALIDA_OBJ
		FROM USER_TABLES
		WHERE TABLE_NAME = 'GD_ENT_CAPITAL_CRED_M91B';

		DBMS_OUTPUT.put_line('GD_ENT_CAPITAL_CRED_M91B - ' || VALIDA_OBJ);

		if VALIDA_OBJ > 0 then
			DBMS_OUTPUT.put_line('drop table GD_ENT_CAPITAL_CRED_M91B');
			execute immediate 'drop table GD_ENT_CAPITAL_CRED_M91B';
			DBMS_OUTPUT.put_line('drop table GD_ENT_CAPITAL_CRED_M91B - end');
		end if;

		DBMS_OUTPUT.put_line('create table as GD_ENT_CAPITAL_CRED_M91B');
		execute immediate 
			q'{create table GD_ENT_CAPITAL_CRED_M91B as
			SELECT /*+ ordered */
				CAPITAL.CDPERSON
				,NVL(SUM(DECODE(CAPITAL.CDTIPGAR, 'A', (CAPITAL.IMPCONCO * CAPITAL.CAMBIO * DECODE(CAPITAL.INDCOASEG, 'N', 1, 1 - (CAPITAL.PERCENTAGEM_TOTAL_COAS / 100))), 0)), 0) CAPITAL_DINAMICO
				,NVL(SUM(CASE 
							WHEN CAPITAL.CDTIPGAR != 'A'
								AND CAPITAL.CDTIPRAM = 1
								THEN (CAPITAL.IMPCONCO * CAPITAL.CAMBIO * DECODE(CAPITAL.INDCOASEG, 'N', 1, 1 - (CAPITAL.PERCENTAGEM_TOTAL_COAS / 100)))
							ELSE 0
							END), 0) CAPITAL_NOMINATIVO
				,NVL(SUM(CASE 
							WHEN CAPITAL.CDTIPGAR != 'A'
								AND CAPITAL.SWESTADO IN (
									'PR'
									,'M'
									)
								AND CAPITAL.CDTIPRAM = 1
								THEN (CAPITAL.IMPCONCO * CAPITAL.CAMBIO * DECODE(CAPITAL.INDCOASEG, 'N', 1, 1 - (CAPITAL.PERCENTAGEM_TOTAL_COAS / 100)))
							ELSE 0
							END), 0) CAPITAL_NOMINATIVO_TOM
