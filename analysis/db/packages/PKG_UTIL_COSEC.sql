			--AND trunc(garantia.FEVIGENC(+)) != NVL(trunc(garantia.FEfinvig(+)), TO_DATE('31-12-2999', 'DD-MM-YYYY'))
			AND NVL(garantia.NMGARANT, 1) = (
				SELECT NVL(MIN(NMGARANT), 1)
