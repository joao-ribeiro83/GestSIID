FUNCTION GET_CHKDIGIT_ADC97(P_VALOR IN VARCHAR2) RETURN VARCHAR2
IS
  NRESULT NUMBER:=0;
  NPRODUTO NUMBER;
  NLENGTH NUMBER:=LENGTH(P_VALOR);
  CPROCESS VARCHAR2(100):=P_VALOR;
BEGIN
  WHILE NLENGTH > 0 LOOP
    NPRODUTO:=SUBSTR(CPROCESS,1,1)*MOD(POWER(10,NLENGTH+1),97);
    CPROCESS:=SUBSTR(CPROCESS,2);
    NRESULT:= NRESULT+NPRODUTO;
    NLENGTH:= NLENGTH-1;
  END LOOP;
  RETURN LTRIM(TO_CHAR(98-MOD(NRESULT,97),'00'));
END GET_CHKDIGIT_ADC97;
