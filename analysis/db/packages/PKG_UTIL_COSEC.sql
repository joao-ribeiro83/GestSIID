/*
-* NOME      : GET_ATRIB_PROP_ANT_201
-* OBJECTIVO : RETORNA O VALOR ANTERIOR DE UM ATRIBUTO DA TABELA CO_MVM_DIT NAO CONSIDERANDO REGISTOS COM ESTADPED = 04,05,06,07
-* AUTOR     : JOAO RIBEIRO
-* DATA      : 03-03-2016
-* VERSAO    : 1.0
-* UTILIZACAO: 
-*
-* ULTIMAS ALTERACOES
-*
-*   DATA       AUTOR           DESCRICAO
-*   ========== =============== =================================================
-*
-*/
FUNCTION GET_ATRIB_PROP_ANT_201 (PI_NMPROPUE IN NUMBER, PI_DTENTRAD IN DATE, PI_TIPO IN NUMBER) RETURN NUMBER IS

V_FACANPRV CO_MVM_DIT.FACANPRV%TYPE := NULL;
V_IMPSOLCO CO_MVM_DIT.IMPSOLCO%TYPE := NULL;
V_IMPCONCO CO_MVM_DIT.IMPCONCO%TYPE := NULL;

BEGIN

	SELECT NVL(FACANPRV,'0') FACANPRV
		,NVL(DECODE(NVL(IMPCONCO,0),0,IMPSOLCO,IMPCONCO),0) IMPSOLCO
		,NVL(IMPCONCO,0) IMPCONCO
	INTO V_FACANPRV
		,V_IMPSOLCO
		,V_IMPCONCO
	FROM (
		SELECT mov_proposta.NMPROPUE
			,mov_proposta.DTENTRAD
			,mov_proposta.FACANPRV
			,mov_proposta.IMPCONCO
			,mov_proposta.IMPSOLCO
			,row_number() OVER (
				ORDER BY mov_proposta.DTENTRAD DESC
				) rn
		FROM CO_MVM_DIT mov_proposta
		WHERE 1 = 1
			AND NOT (
				mov_proposta.TPENTRAD = 'A'
				AND mov_proposta.SWALTTO = 'N'
				AND mov_proposta.SWALTFA = 'N'
				AND mov_proposta.SWALTCP = 'N'
				AND mov_proposta.SWALTGC = 'N'
				AND mov_proposta.SWALTMS = 'N'
				AND mov_proposta.SWALTOU = 'S'
				)
			AND mov_proposta.ESTADPED NOT IN (
				'04'
				,'05'
				,'06'
				,'07'
				)
			AND mov_proposta.NMPROPUE = PI_NMPROPUE
			AND TRUNC(mov_proposta.DTENTRAD) < PI_DTENTRAD
		)
	WHERE rn = 1
	;

	IF PI_TIPO = 1 THEN RETURN to_number(REPLACE(V_FACANPRV, '.', ','));
	ELSIF PI_TIPO = 2 THEN RETURN V_IMPSOLCO;
	ELSE RETURN V_IMPCONCO;
	end if;

EXCEPTION
  WHEN NO_DATA_FOUND THEN
	 RETURN 0;
  WHEN OTHERS THEN
     RETURN null;

END GET_ATRIB_PROP_ANT_201;

