/*
-* NOME      : GET_INFO_ENTIDADE_DT
-* OBJECTIVO : RETORNA A INFORMACAO DE UMA ENTIDADE DA APOLICE NA DATA INDICADA
-* AUTOR     : JOAO RIBEIRO
-* DATA      : 22-07-2016
-* VERSAO    : 1.0
-* UTILIZACAO: PI_TIPO: 1-DSNOMBRE, 2-CDIDEPER, 3-CDCAE, 4-DSPORT
-*
-* ULTIMAS ALTERACOES
-*
-*   DATA       AUTOR           DESCRICAO
-*   ========== =============== =================================================
-*
-*/
FUNCTION GET_INFO_ENTIDADE_DT ( PI_CDUNIECO IN NUMBER
                              , PI_CDRAMO   IN VARCHAR2
                              , PI_ESTADO   IN VARCHAR2
                              , PI_NMPOLIZA IN NUMBER
                              , PI_DATA     IN DATE DEFAULT SYSDATE
							  , PI_CDROL	IN VARCHAR2
							  , PI_TIPO		IN NUMBER) RETURN VARCHAR2 IS

V_CDIDEPER MPERSONA.CDIDEPER%TYPE :=NULL;
V_DSNOMBRE MPERSONA.DSNOMBRE%TYPE :=NULL;
V_CDCAE CO_ENTIDAD.CDCAE%TYPE :=NULL;
V_DSPORT CO_CAES.DSPORT%TYPE :=NULL;


BEGIN

	SELECT DADOS_ENTIDADE.DSNOMBRE
		,DADOS_ENTIDADE.CDIDEPER
		,CAE.CDCAE
		,DESCCAE.DSPORT
	INTO V_DSNOMBRE
		,V_CDIDEPER
		,V_CDCAE
		,V_DSPORT
	FROM MPOLIPER ENTIDADE
		,MPERSONA DADOS_ENTIDADE
		,CO_ENTIDAD CAE
		,CO_CAES DESCCAE
	WHERE 1 = 1
		AND DESCCAE.cdcae(+) = CAE.cdcae
		AND CAE.cdperson(+) = ENTIDADE.cdperson
		AND DADOS_ENTIDADE.cdperson(+) = ENTIDADE.cdperson
		AND ENTIDADE.nmpoliza = PI_NMPOLIZA
		AND ENTIDADE.estado = PI_ESTADO
		AND ENTIDADE.cdramo = PI_CDRAMO
		AND ENTIDADE.cdunieco = PI_CDUNIECO
		AND ENTIDADE.cdrol = PI_CDROL
		AND NVL(ENTIDADE.nmsuplem, 0) = (
			SELECT NVL(MAX(x.nmsuplem), 0)
			FROM mpoliper x
			WHERE x.nmsuplem <= DECODE(PI_DATA, NULL, TO_CHAR(SYSDATE, 'J'), TO_CHAR(PI_DATA, 'J')) || '99999999999'
				AND x.nmpoliza = ENTIDADE.nmpoliza
				AND x.cdramo = ENTIDADE.cdramo
				AND x.cdunieco = ENTIDADE.cdunieco
				AND x.estado = ENTIDADE.estado
				AND x.cdrol = ENTIDADE.cdrol
				AND (
					x.cdunieco
					,x.cdramo
					,x.estado
					,x.nmpoliza
					,x.nmsuplem
					) NOT IN (
					SELECT cdunieco
						,cdramo
						,estado
						,nmpoliza
						,nmsuplem
					FROM GD_APOLICES_WORKING_DIT_VW
					)
			)
	;

	IF (PI_TIPO = 1) THEN
		RETURN V_DSNOMBRE;
	ELSIF (PI_TIPO = 2) THEN
		RETURN V_CDIDEPER;
	ELSIF (PI_TIPO = 3) THEN
		RETURN V_CDCAE;
	ELSIF (PI_TIPO = 4) THEN
		RETURN V_DSPORT;
	ELSE RETURN NULL;
	END IF;

EXCEPTION
  WHEN NO_DATA_FOUND THEN
	 RETURN '';
  WHEN OTHERS THEN
     RETURN null;

END GET_INFO_ENTIDADE_DT;

/*
-* NOME      : GET_INFO_CESSIONARIOS_DT
-* OBJECTIVO : RETORNA A INFORMACAO DE CESSIONARIOS DA APOLICE NA DATA INDICADA
-* AUTOR     : JOAO RIBEIRO
-* DATA      : 22-07-2016
-* VERSAO    : 1.0
-* UTILIZACAO: PI_TIPO: 1-NUMERO DE CESSIONARIO, 2-NOME DO CESSIONARIO, 3-PERCENTAGEM DE CESSAO
-*
-* ULTIMAS ALTERACOES
-*
-*   DATA       AUTOR           DESCRICAO
-*   ========== =============== =================================================
-*
-*/
FUNCTION GET_INFO_CESSIONARIOS_DT ( PI_CDUNIECO IN NUMBER
                              , PI_CDRAMO   IN VARCHAR2
                              , PI_ESTADO   IN VARCHAR2
                              , PI_NMPOLIZA IN NUMBER
                              , PI_DATA     IN DATE DEFAULT SYSDATE
							  , PI_TIPO		IN NUMBER) RETURN VARCHAR2 IS

V_NUMERO MPERSONA.CDIDEPER%TYPE :=NULL;
V_DSNOMBRE MPERSONA.DSNOMBRE%TYPE :=NULL;
V_PERC_CESSAO MPERSONA.CDIDEPER%TYPE :=NULL;

BEGIN

	SELECT TO_CHAR(a.numero)
		,b.dsnombre nome_cessionario
		,TO_CHAR(a.somatorio)
	INTO V_NUMERO
	,V_DSNOMBRE
	,V_PERC_CESSAO
	FROM (
		SELECT cdunieco
			,cdramo
			,estado
			,nmpoliza
			,numero
			,decode(numero, 1, cdperson, NULL) cdperson
			,somatorio
		FROM (
			SELECT cdunieco
				,cdramo
				,estado
				,nmpoliza
				,count(cdperson) numero
				,max(cdperson) cdperson
				,sum(otvalor) somatorio
			FROM (
				SELECT ce.cdunieco
					,ce.cdramo
					,ce.estado
					,ce.nmpoliza
					,ce.cdperson
					,to_number(replace(ce.otvalor, '.', ',')) otvalor
				FROM co_tvaloprol ce
				WHERE 1 = 1
					AND ce.cdatribu = 1
					AND ce.cdrol = 'CE'
					AND ce.STATUS = 'V'
					AND ce.nmpoliza = PI_NMPOLIZA
					AND ce.estado = PI_ESTADO
					AND ce.CDRAMO = PI_CDRAMO
					AND ce.cdunieco = PI_CDUNIECO
					AND ce.nmsuplem = (
						SELECT max(x.nmsuplem)
						FROM co_tvaloprol x
						WHERE x.cdunieco = ce.cdunieco
							AND x.cdramo = ce.cdramo
							AND x.estado = ce.estado
							AND x.nmpoliza = ce.nmpoliza
							AND x.cdperson = ce.cdperson
							AND x.cdatribu = ce.cdatribu
							AND x.cdrol = ce.cdrol
							AND x.nmsuplem <= DECODE(PI_DATA, NULL,TO_CHAR(SYSDATE,'J'),TO_CHAR(PI_DATA,'J'))||'99999999999'
						)
					AND (
						ce.cdunieco
						,ce.cdramo
						,ce.estado
						,ce.nmpoliza
						,ce.nmsuplem
						) NOT IN (
						SELECT cdunieco
							,cdramo
							,estado
							,nmpoliza
							,nmsuplem
						FROM GD_APOLICES_WORKING_DIT_VW
						)
				)
			GROUP BY cdunieco
				,cdramo
				,estado
				,nmpoliza
			)
		) a
		,mpersona b
	WHERE NVL(a.cdperson, 0) = b.cdperson(+)
	;

	IF (PI_TIPO = 1) THEN
		RETURN V_NUMERO;
	ELSIF (PI_TIPO = 2) THEN
		RETURN V_DSNOMBRE;
	ELSIF (PI_TIPO = 3) THEN
		RETURN V_PERC_CESSAO;
	ELSE RETURN NULL;
	END IF;

EXCEPTION
  WHEN NO_DATA_FOUND THEN
	 RETURN '';
  WHEN OTHERS THEN
     RETURN null;

END GET_INFO_CESSIONARIOS_DT;


