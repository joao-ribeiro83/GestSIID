/*
-* NOME      : GET_MONT_GARANT_DATA
-* OBJECTIVO : RETORNA O MONTANTE SOLICITADO/CONCEDIDO A UMA DATA EXPECIFICA
-* UTILIZACAO: PI_TIPO = 1 define se o montante pedido e o solicitado, 2 para o montante concedido
-* AUTOR     : JOAO RIBEIRO
-* DATA      : 10-01-2016
-* VERSAO    : 1.0
-*
-* ULTIMAS ALTERACOES
-*
-*   DATA       AUTOR           DESCRICAO
-*   ========== =============== =================================================
-*
-*/
FUNCTION GET_MONT_GARANT_DATA (PI_CDUNIECO IN NUMBER, PI_CDRAMO IN NUMBER, PI_NMPOLIZA IN NUMBER, PI_DATE IN DATE, PI_TIPO IN NUMBER) RETURN NUMBER IS

V_IMPSOLCO co_progar.impsolco%TYPE := NULL;
V_IMPCONCO co_progar.impconco%TYPE := NULL;
V_IMPSOLCO2 co_progar.impsolco%TYPE := NULL;
V_IMPCONCO2 co_progar.impconco%TYPE := NULL;

BEGIN

	IF PI_DATE is null then return null;
	else 
		select MAX(garantia.impsolco), MAX(garantia.impconco)
		into V_IMPSOLCO, V_IMPCONCO
		from co_progar garantia
		where garantia.cdunieco = PI_CDUNIECO
		and garantia.cdramo = PI_CDRAMO
		and garantia.nmpoliza = PI_NMPOLIZA
		and garantia.swestado IN (
			'D'
			,'S'
			,'M'
			,'AP'
			,'A'
			,'B'
			--,'DB'
			,'PR'
			)
		AND trunc(garantia.FEVIGENC(+)) != NVL(trunc(garantia.FEfinvig(+)), TO_DATE('31-12-2999', 'DD-MM-YYYY'))
		AND trunc(garantia.FEVIGENC) <= PI_DATE
		AND NVL(garantia.NMGARANT, 1) = (
			SELECT NVL(MAX(NMGARANT), 1)
			FROM co_progar X
			WHERE X.nmpoliza(+) = garantia.nmpoliza
				AND X.cdramo(+) = garantia.cdramo
				AND X.cdunieco(+) = garantia.cdunieco
				AND trunc(X.FEVIGENC(+)) != NVL(trunc(X.FEfinvig(+)), TO_DATE('31-12-2999', 'DD-MM-YYYY'))
				AND X.swestado(+) IN (
					'D'
					,'S'
					,'M'
					,'AP'
					,'A'
					,'B'
					--,'DB'
					,'PR'
					)
				AND trunc(X.FEVIGENC(+)) <= PI_DATE
			)
		;

		if (V_IMPSOLCO is null or V_IMPCONCO is null) then

			select garantia.impsolco, garantia.impconco
			into V_IMPSOLCO2, V_IMPCONCO2
			from co_progar garantia
			where garantia.cdunieco = PI_CDUNIECO
			and garantia.cdramo = PI_CDRAMO
			and garantia.nmpoliza = PI_NMPOLIZA
			and garantia.swestado IN (
				'D'
				,'S'
				,'M'
				,'AP'
				,'A'
				,'B'
				--,'DB'
				,'PR'
				)
			--AND trunc(garantia.FEVIGENC(+)) != NVL(trunc(garantia.FEfinvig(+)), TO_DATE('31-12-2999', 'DD-MM-YYYY'))
			AND NVL(garantia.NMGARANT, 1) = (
				SELECT NVL(MIN(NMGARANT), 1)
				FROM co_progar X
				WHERE X.nmpoliza(+) = garantia.nmpoliza
					AND X.cdramo(+) = garantia.cdramo
					AND X.cdunieco(+) = garantia.cdunieco
					--AND trunc(X.FEVIGENC(+)) != NVL(trunc(X.FEfinvig(+)), TO_DATE('31-12-2999', 'DD-MM-YYYY'))
					AND X.swestado(+) IN (
						'D'
						,'S'
						,'M'
						,'AP'
						,'A'
						,'B'
						--,'DB'
						,'PR'
						)
				)
			;
		end if;

		if PI_TIPO = 1 then return NVL(V_IMPSOLCO,V_IMPSOLCO2);
		else return NVL(V_IMPCONCO,V_IMPCONCO2);
		end if;
	end if;

EXCEPTION
  WHEN OTHERS THEN
     RETURN null;

END GET_MONT_GARANT_DATA;

